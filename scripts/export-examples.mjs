import { mkdir, writeFile } from "node:fs/promises";
import { createSnapshot, createCharacter, createTimelineEvent, createRelationship, fact } from "../src/lib/story/factory.ts";
const snapshot=createSnapshot("eastern_wuxia");
snapshot.world.story_id="story_example";snapshot.characters.story_id="story_example";
snapshot.world.title=fact("雪落青崖");snapshot.world.logline=fact("开局的一封来信，让师徒重新面对封山往事。");
snapshot.world.summary=fact("用于 Schema 和交互说明的合成示例，不是固定角色模板。");
snapshot.world.setting.era=fact("承平十三年");snapshot.world.setting.geography=fact("青崖山与山下旧渡口");
const history=createTimelineEvent("封山");history.event_id="event_history";history.order=0;history.time_label=fact("开局三年前");
const opening=createTimelineEvent("一封旧信");opening.event_id="event_opening";opening.period="opening";opening.order=1;opening.time_label=fact("开局之日");opening.after_event_ids=["event_history"];
snapshot.world.timeline=[history,opening];
const student=createCharacter("沈照","npc_student"),master=createCharacter("无名师父","npc_master");
student.identity=fact("失忆剑客");master.identity=fact("隐居的师父");
const relation=createRelationship(student.character_id,master.character_id);relation.relationship_id="rel_mentor";relation.type="mentor";
student.relationship_ids=[relation.relationship_id];master.relationship_ids=[relation.relationship_id];master.timeline_event_ids=[history.event_id];history.related_character_ids=[master.character_id];
snapshot.characters.characters=[student,master];snapshot.characters.relationships=[relation];
await mkdir("examples",{recursive:true});
await writeFile("examples/story_world.json",JSON.stringify(snapshot.world,null,2),"utf8");
await writeFile("examples/character_profiles.json",JSON.stringify(snapshot.characters,null,2),"utf8");
console.log("Wrote synthetic, editable example documents (not default NPC rosters).");
